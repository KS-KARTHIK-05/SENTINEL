#!/usr/bin/env python3
"""Write the E5 robustness and E6 fast-simulator configs with the fitted detector model."""
import json
import sys

import yaml

fitted, outdir = sys.argv[1], sys.argv[2]
det = {k: float(v) for k, v in json.load(open(fitted)).items()}
robust = {
    'tuned_file': 'configs/tuned_v3.yaml',
    'base': {'n_uav': 8, 'duration_s': 600, 'channel': {'profile': 'urban_rubble'},
             'map': {'kind': 'generate', 'size': 400, 'n_targets': 25, 'base': True},
             'policy_path': 'configs/mappo_policy.npz', 'detector': det},
    'grid': {'failures': [{'kind': 'none'}, {'kind': 'single', 't': 240},
                          {'kind': 'simultaneous', 't': 240, 'fraction': 0.3},
                          {'kind': 'cascading', 't': 180, 'k': 3, 'gap': 60},
                          {'kind': 'poisson', 'rate': 0.02},
                          {'kind': 'brownout', 't': 180, 'duration': 120, 'drop_db': 20}]},
    'methods': ['sentinel', 'B0_pso', 'B1_v1', 'B2_commpso', 'B3_lambda2', 'B4_potential',
                'B5_mappo', 'B6_lawnmower', 'B7_wall', 'B8_relay'],
    'seeds': 30}
e6 = {
    'tuned_file': 'configs/tuned.yaml',
    'base': {'n_uav': 3, 'duration_s': 300, 'channel': {'profile': 'urban_rubble'},
             'map': {'kind': 'generate', 'size': 100, 'n_targets': 20, 'base': True},
             'failures': {'kind': 'single', 't': 150, 'uav': 1}, 'detector': det},
    'methods': ['sentinel', 'B0_pso'], 'seeds': 10}
hdr = '# Generated by scripts/overnight/make_fitted_configs.py from {} (E5 fit).\n'.format(fitted)
with open(f'{outdir}/robust_fitted.yaml', 'w') as f:
    f.write(hdr + '# E5 robustness: Table 2 urban settings with the fitted detector model.\n')
    yaml.safe_dump(robust, f, sort_keys=False)
with open(f'{outdir}/e6_fastsim.yaml', 'w') as f:
    f.write(hdr + '# E6 fast-simulator side: worlds 0-9 of the PX4 check, fitted detector.\n')
    yaml.safe_dump(e6, f, sort_keys=False)
print('wrote robust_fitted.yaml, e6_fastsim.yaml')
