#!/usr/bin/env python3
"""Write the E5 robustness and E6 fast-simulator configs with the fitted detector model.

The fit gives ``fp_per_debris_item`` (false-alarm candidates per look per debris item in view).
The simulator's ``fp_rate`` counts candidates per look over the whole world (each lands on a
debris item drawn from all of the world's items), so it is set per configuration from the number
of debris items in that configuration's worlds (seeds 0 to seeds-1, generated as the simulator
does; the count must be the same in every world).

    python make_fitted_configs.py <detector_fitted.json> <config folder> [--suffix _v2]
"""
from __future__ import annotations

import argparse
import json

import numpy as np
import yaml


def n_debris(map_cfg: dict, seeds: int) -> int:
    """Debris items per world of a generated-map configuration (as ``sentinel_sim.sim``)."""
    from sentinel_sim import world as W
    n = set()
    for s in range(seeds):
        r_world = np.random.default_rng(np.random.SeedSequence(s).spawn(5)[0])
        w = W.generate(map_cfg['size'], map_cfg['n_targets'], r_world,
                       n_moving=map_cfg.get('n_moving', 0), base=map_cfg.get('base', True),
                       buried=map_cfg.get('buried', 1))
        n.add(len(w.clutter_xy))
    assert len(n) == 1, f'debris count varies across worlds: {sorted(n)}'
    return n.pop()


def detector_for(fitted: dict, map_cfg: dict, seeds: int) -> dict:
    """Simulator detector parameters for one configuration."""
    det = {k: float(v) for k, v in fitted.items() if k != 'fp_per_debris_item'}
    det['fp_rate'] = float(fitted['fp_per_debris_item']) * n_debris(map_cfg, seeds)
    return det


def configs(fitted: dict) -> dict:
    robust = {
        'tuned_file': 'configs/tuned_v3.yaml',
        'base': {'n_uav': 8, 'duration_s': 600, 'channel': {'profile': 'urban_rubble'},
                 'map': {'kind': 'generate', 'size': 400, 'n_targets': 25, 'base': True},
                 'policy_path': 'configs/mappo_policy.npz'},
        'grid': {'failures': [{'kind': 'none'}, {'kind': 'single', 't': 240},
                              {'kind': 'simultaneous', 't': 240, 'fraction': 0.3},
                              {'kind': 'cascading', 't': 180, 'k': 3, 'gap': 60},
                              {'kind': 'poisson', 'rate': 0.02},
                              {'kind': 'brownout', 't': 180, 'duration': 120, 'drop_db': 20}]},
        'methods': ['sentinel', 'B0_pso', 'B1_v1', 'B2_commpso', 'B3_lambda2', 'B4_potential',
                    'B5_mappo', 'B6_lawnmower', 'B7_wall', 'B8_relay'],
        'seeds': 30}
    e6 = {
        'tuned_file': 'configs/tuned.yaml',
        'base': {'n_uav': 3, 'duration_s': 300, 'channel': {'profile': 'urban_rubble'},
                 'map': {'kind': 'generate', 'size': 100, 'n_targets': 20, 'base': True},
                 'failures': {'kind': 'single', 't': 150, 'uav': 1}},
        'methods': ['sentinel', 'B0_pso'], 'seeds': 10}
    for c in (robust, e6):
        c['base']['detector'] = detector_for(fitted, c['base']['map'], c['seeds'])
    return {'robust_fitted': robust, 'e6_fastsim': e6}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('fitted')
    ap.add_argument('outdir')
    ap.add_argument('--suffix', default='')
    a = ap.parse_args()
    fitted = json.load(open(a.fitted))
    cfg = configs(fitted)
    hdr = f'# Generated by scripts/overnight/make_fitted_configs.py from {a.fitted} (E5 fit).\n'
    what = {'robust_fitted': '# E5 robustness: Table 2 urban settings with the fitted detector model.\n',
            'e6_fastsim': '# E6 fast-simulator side: worlds 0-9 of the PX4 check, fitted detector.\n'}
    for name, c in cfg.items():
        rate = c['base']['detector']['fp_rate']
        n = round(rate / fitted['fp_per_debris_item'])
        with open(f'{a.outdir}/{name}{a.suffix}.yaml', 'w') as f:
            f.write(hdr + what[name] + f'# fp_rate = fp_per_debris_item x {n} debris items per world.\n')
            yaml.safe_dump(c, f, sort_keys=False)
        print(f'wrote {name}{a.suffix}.yaml (fp_rate {rate:.3f}, {n} debris items per world)')


if __name__ == '__main__':
    main()
