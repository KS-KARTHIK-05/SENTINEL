    a = df[df.cfg_map_size == 400]
    ns = sorted(a.cfg_n_uav.unique())
    cols = [(f'$N={n}$', {m: per_seed(a[a.cfg_n_uav == n], m) for m in [REF] + BASE}) for n in ns]
    rows = table(cols, [REF] + BASE, NAMES)
    write('tab_e1.tex',
          '\\begin{table}[t]\\centering\\caption{Victims reported within 60\\,s vs.\\ swarm size '
          '(400\\,m, urban rubble, Poisson failures). ' + CAPSTAT + '}\\label{tab:e1}\n'
          '\\scriptsize\\setlength{\\tabcolsep}{1.6pt}\\begin{tabular}{lccccc}\\toprule\n'
          'Method & ' + ' & '.join(h for h, _ in cols) + '\\\\\\midrule\n' + '\n'.join(rows)
          + '\n\\bottomrule\\end{tabular}\\end{table}\n')
    mac('EoneNmin', ns[0]); mac('EoneNmax', ns[-1])
    # 200 m area: dense-contact regime vs MAPPO
    b = df[(df.cfg_map_size == 200)]
    sig = []
