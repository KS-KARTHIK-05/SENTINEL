def mission_count() -> None:
    n = 0
    for f in glob.glob(os.path.join(RES, 'e*', 'summary.parquet')):
        if not os.path.basename(os.path.dirname(f)).endswith('_oldmetric'):
            n += len(pd.read_parquet(f))
    mac('Missions', f'{round(n, -3):,}'.replace(',', '\\,'))


